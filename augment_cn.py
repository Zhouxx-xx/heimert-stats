# 按效果类型分组（方便阅读）
AUGMENT_TYPE_MAP: dict[int, str] = {}

# 按稀有度分组（1=普通, 2=稀有, 3=史诗, 4=传说）
AUGMENT_RARITY_MAP: dict[int, int] = {}


def get_augment_name(augment_id: int) -> Optional[str]:
    """获取增幅的中文名称，未知 ID 返回 None"""
    if augment_id == 0:
        return None
    return AUGMENT_NAME_MAP.get(augment_id)


def get_augment_display(augment_id: int) -> str:
    """
    获取增幅的显示文本。
    优先显示中文名，否则显示英文 ID。
    """
    if augment_id == 0:
        return ""
    name = AUGMENT_NAME_MAP.get(augment_id)
    if name:
        return name
    return f"增幅#{augment_id}"


def load_augment_map_from_lcu(lcu_client=None) -> int:
    """
    从 LCU 客户端加载增幅数据到内存映射。
    需要 LCU 连接可用时调用。
    返回加载的增幅数量。
    """
    if lcu_client is None:
        return 0
    try:
        data = lcu_client._request("GET", "/lol-game-data/assets/v1/mayhemaugments.json")
        if not data:
            return 0
        count = 0
        for item in data:
            aid = item.get("id")
            name = item.get("name", "")
            if aid and name:
                AUGMENT_NAME_MAP[aid] = name
                count += 1
        logger.info(f"从 LCU 加载了 {count} 个增幅数据")
        return count
    except Exception as e:
        logger.warning(f"从 LCU 加载增幅数据失败: {e}")
        return 0
